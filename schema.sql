  public.kategori_anggaran,
  public.anggaran,
  public.realisasi
to anon;
grant usage, select on all sequences in schema public to anon;

create or replace function public.check_realization_budget_limit()
returns trigger
language plpgsql
as $$
declare
  allocation_amount numeric(16, 2);
  already_spent numeric(16, 2);
begin
  select jumlah_anggaran into allocation_amount
  from public.anggaran
  where id = new.anggaran_id
  for update;

  if not found then
    raise exception 'Alokasi anggaran tidak ditemukan.' using errcode = '23503';
  end if;

  select coalesce(sum(jumlah), 0) into already_spent
  from public.realisasi
  where anggaran_id = new.anggaran_id
    and (tg_op <> 'UPDATE' or id <> new.id);

  if already_spent + new.jumlah > allocation_amount then
    raise exception 'Realisasi melebihi sisa anggaran pada alokasi ini.' using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists realisasi_budget_limit on public.realisasi;
create trigger realisasi_budget_limit
before insert or update of anggaran_id, jumlah on public.realisasi
for each row execute function public.check_realization_budget_limit();


create table if not exists public.unit_organisasi (
  id bigint generated by default as identity primary key,
  nama text not null unique,
  penanggung_jawab text,
  created_at timestamptz not null default now()
);

create table if not exists public.kategori_anggaran (
  id bigint generated by default as identity primary key,
  nama text not null unique,
  warna text not null default '#c94e79',
  created_at timestamptz not null default now()
);

create table if not exists public.anggaran (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.unit_organisasi(id) on delete restrict,
  kategori_id bigint not null references public.kategori_anggaran(id) on delete restrict,
  tahun integer not null check (tahun between 2000 and 2100),
  jumlah_anggaran numeric(16, 2) not null check (jumlah_anggaran > 0),
  catatan text,
  created_at timestamptz not null default now(),
  constraint anggaran_unit_kategori_tahun_unique unique (unit_id, kategori_id, tahun)
);

create table if not exists public.realisasi (
  id bigint generated by default as identity primary key,
  anggaran_id bigint not null references public.anggaran(id) on delete cascade,
  tanggal date not null default current_date,
  uraian text not null,
  jumlah numeric(16, 2) not null check (jumlah > 0),
  nomor_bukti text,
  created_at timestamptz not null default now()
);

create index if not exists anggaran_tahun_idx on public.anggaran(tahun);
create index if not exists realisasi_anggaran_tanggal_idx on public.realisasi(anggaran_id, tanggal desc);

alter table public.unit_organisasi disable row level security;
alter table public.kategori_anggaran disable row level security;
alter table public.anggaran disable row level security;
alter table public.realisasi disable row level security;

grant usage on schema public to anon;

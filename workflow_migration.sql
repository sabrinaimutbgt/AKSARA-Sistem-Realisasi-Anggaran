create or replace function public.review_reimbursement(reimbursement_id bigint, decision text, review_note text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.current_user_role() not in ('bendahara', 'admin') then
    raise exception 'Hanya bendahara atau admin yang dapat meninjau pengajuan.' using errcode = '42501';
  end if;
  if decision not in ('disetujui', 'ditolak') then
    raise exception 'Keputusan tidak valid.' using errcode = '22023';
  end if;
  update public.reimbursements
  set status = decision,
      catatan_persetujuan = nullif(trim(review_note), ''),
      diputuskan_oleh = (select auth.uid()),
      diputuskan_pada = now()
  where id = reimbursement_id and status = 'menunggu';
  if not found then
    raise exception 'Pengajuan tidak ditemukan atau sudah ditinjau.' using errcode = 'P0002';
  end if;
end;
$$;

create or replace function public.mark_reimbursement_paid(reimbursement_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  reimbursement public.reimbursements%rowtype;
  realization_key bigint;
begin
  if public.current_user_role() not in ('bendahara', 'admin') then
    raise exception 'Hanya bendahara atau admin yang dapat memproses pembayaran.' using errcode = '42501';
  end if;

  select * into reimbursement
  from public.reimbursements
  where id = reimbursement_id
  for update;

  if not found then
    raise exception 'Pengajuan reimburse tidak ditemukan.' using errcode = 'P0002';
  end if;
  if reimbursement.status <> 'disetujui' then
    raise exception 'Hanya pengajuan yang disetujui yang dapat dibayar.' using errcode = '23514';
  end if;
  if not exists (
    select 1
    from public.anggaran as allocation
    join public.program_kerja as program on program.id = reimbursement.proker_id
    where allocation.id = reimbursement.anggaran_id
      and allocation.unit_id = reimbursement.unit_id
      and program.unit_id = reimbursement.unit_id
  ) then
    raise exception 'Proker dan alokasi harus berasal dari divisi pemohon.' using errcode = '23514';
  end if;

  insert into public.realisasi (anggaran_id, tanggal, uraian, jumlah, nomor_bukti)
  values (
    reimbursement.anggaran_id,
    reimbursement.tanggal_pengeluaran,
    reimbursement.uraian,
    reimbursement.jumlah,
    reimbursement.nomor_bukti
  )
  returning id into realization_key;

  update public.reimbursements
  set status = 'dibayar',
      dibayar_oleh = (select auth.uid()),
      dibayar_pada = now(),
      realisasi_id = realization_key
  where id = reimbursement.id;
end;
$$;


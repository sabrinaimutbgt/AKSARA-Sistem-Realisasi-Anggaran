create or replace function public.assign_profile_access(profile_id uuid, assigned_role text, assigned_unit_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.current_user_role() <> 'admin' then
    raise exception 'Hanya admin yang dapat mengatur peran dan divisi.' using errcode = '42501';
  end if;
  if assigned_role not in ('anggota', 'bendahara', 'admin') then
    raise exception 'Peran tidak valid.' using errcode = '22023';
  end if;
  update public.profiles
  set peran = assigned_role, unit_id = assigned_unit_id
  where id = profile_id;
  if not found then
    raise exception 'Profil tidak ditemukan.' using errcode = 'P0002';
  end if;
end;
$$;


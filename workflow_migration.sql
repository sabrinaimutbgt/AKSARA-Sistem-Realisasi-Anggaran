create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nama text not null default '',
  unit_id bigint references public.unit_organisasi(id) on delete set null,
  peran text not null default 'anggota' check (peran in ('anggota', 'bendahara', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.program_kerja (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.unit_organisasi(id) on delete restrict,
  nama text not null,
  aktif boolean not null default true,
  created_at timestamptz not null default now(),
  unique (unit_id, nama)
);

create table if not exists public.reimbursements (
  id bigint generated by default as identity primary key,
  pemohon_id uuid not null references public.profiles(id) on delete restrict,
  unit_id bigint not null references public.unit_organisasi(id) on delete restrict,
  proker_id bigint not null references public.program_kerja(id) on delete restrict,
  anggaran_id bigint not null references public.anggaran(id) on delete restrict,
  tanggal_pengeluaran date not null,
  uraian text not null,
  jumlah numeric(16, 2) not null check (jumlah > 0),
  nomor_bukti text,
  catatan_pemohon text,
  status text not null default 'menunggu' check (status in ('menunggu', 'disetujui', 'ditolak', 'dibayar')),
  catatan_persetujuan text,
  diputuskan_oleh uuid references public.profiles(id) on delete set null,
  diputuskan_pada timestamptz,
  dibayar_oleh uuid references public.profiles(id) on delete set null,
  dibayar_pada timestamptz,
  realisasi_id bigint unique references public.realisasi(id) on delete set null,
  created_at timestamptz not null default now()
);


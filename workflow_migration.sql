create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_unit_id bigint;
begin
  select id into selected_unit_id
  from public.unit_organisasi
  where nama = new.raw_user_meta_data ->> 'unit_nama';

  insert into public.profiles (id, nama, unit_id)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nama', split_part(new.email, '@', 1)),
    selected_unit_id
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute function public.handle_new_auth_user();

insert into public.profiles (id, nama, unit_id)
select
  auth_user.id,
  coalesce(auth_user.raw_user_meta_data ->> 'nama', split_part(auth_user.email, '@', 1)),
  unit.id
from auth.users as auth_user
left join public.unit_organisasi as unit
  on unit.nama = auth_user.raw_user_meta_data ->> 'unit_nama'
on conflict (id) do nothing;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select peran from public.profiles where id = (select auth.uid());
$$;

